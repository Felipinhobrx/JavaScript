/*
Operadores de comparação
> Maior
>= Maior ou igual
< Menor
<= Menor ou igual
== Igual
=== Estritamente igual
!= Diferente
!== Diferente estrito
*/

console.log(10 > 9)//true
console.log(10 >= 10)//true

console.log(10 < 11)//true
console.log(10 <= 11)//true

console.log(10 == '10')//true
console.log(10 === '10')//false

console.log(10 != '10')//false
console.log(10 !== '10')//true